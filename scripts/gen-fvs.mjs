// Write src/data/fvs.ts, the FVS registry the package ships, from the vendored
// data: mongfontbuilder's variants.json (which forms each writing system
// registers) and UCD 18.0 (code points, and the sequences marked "not in use").
// Run with `bun run gen:fvs`; test/fvs.test.ts fails when the file is stale.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const UNICODE_VERSION = '18.0.0';
const OUT = 'src/data/fvs.ts';

const read = (path) => readFileSync(`${ROOT}${path}`, 'utf8');

const SELECTORS = new Map([
  [0x180b, 1],
  [0x180c, 2],
  [0x180d, 3],
  [0x180f, 4],
]);
const POSITIONS = ['isol', 'init', 'medi', 'fina'];

function codePointsByName() {
  const map = new Map();
  for (const line of read(`vendor/unicode/UnicodeData-${UNICODE_VERSION}-mongolian.txt`).split(
    '\n',
  )) {
    const [hex, name] = line.split(';');
    if (hex && name) map.set(name, Number.parseInt(hex, 16));
  }
  return map;
}

/** Mongolian lines of StandardizedVariants.txt as { base, fvs, notInUse }. */
export function readStandardizedVariants() {
  const rows = [];
  for (const line of read(`vendor/unicode/StandardizedVariants-${UNICODE_VERSION}.txt`).split(
    '\n',
  )) {
    const data = line.split('#')[0]?.trim();
    if (!data) continue;
    const [sequence = '', label = '', positions = ''] = data.split(';').map((f) => f.trim());
    const [base, selector] = sequence.split(/\s+/).map((h) => Number.parseInt(h, 16));
    const fvs = SELECTORS.get(selector);
    if (base === undefined || fvs === undefined) continue;
    rows.push({
      base,
      fvs,
      notInUse: label === 'not in use',
      // Blank for U+1880/U+1881: a parser that requires positions drops them.
      positions: positions ? positions.split(/\s+/).map((p) => p.slice(0, 4)) : [],
    });
  }
  return rows;
}

const byKey = (a, b) =>
  a.base - b.base || POSITIONS.indexOf(a.position) - POSITIONS.indexOf(b.position) || a.fvs - b.fvs;

/** The registry as plain data, the same shape `src/data/fvs.ts` exports. */
export function deriveFvs() {
  const names = codePointsByName();
  const variants = JSON.parse(read('vendor/mongfontbuilder/variants.json'));
  const hudum = [];
  const otherKeys = new Map();
  for (const [name, positions] of Object.entries(variants)) {
    const base = names.get(name);
    if (base === undefined)
      throw new Error(`no code point for ${name} in the vendored UnicodeData`);
    for (const [position, forms] of Object.entries(positions)) {
      for (const [key, form] of Object.entries(forms)) {
        // Key "0" is a form reached by context alone, not FVS0.
        if (key === '0') continue;
        const fvs = Number(key);
        const mng = form.locales.MNG;
        if (mng) {
          hudum.push({
            base,
            position,
            fvs,
            selectsDefault: form.default === true,
            ...(mng.archaic ? { archaic: true } : {}),
            ...(mng.unrecommended ? { unrecommended: true } : {}),
          });
        } else {
          otherKeys.set(`${base} ${position} ${fvs}`, { base, position, fvs });
        }
      }
    }
  }
  const notInUse = readStandardizedVariants()
    .filter((row) => row.notInUse)
    .map(({ base, fvs }) => ({ base, fvs }));
  return {
    hudum: hudum.sort(byKey),
    otherWritingSystems: [...otherKeys.values()].sort(byKey),
    notInUse: notInUse.sort((a, b) => a.base - b.base || a.fvs - b.fvs),
  };
}

const hex = (n) => `0x${n.toString(16)}`;

function render({ hudum, otherWritingSystems, notInUse }) {
  const reg = (r) =>
    `{ base: ${hex(r.base)}, position: '${r.position}', fvs: ${r.fvs}, selectsDefault: ${r.selectsDefault}` +
    `${r.archaic ? ', archaic: true' : ''}${r.unrecommended ? ', unrecommended: true' : ''} },`;
  return `// GENERATED by scripts/gen-fvs.mjs — do not edit. Regenerate with \`bun run gen:fvs\`.
// Sources: vendor/mongfontbuilder/variants.json and vendor/unicode/ (UCD ${UNICODE_VERSION}).
import type { FvsRegistration, JoiningPosition } from '../types.js';

/** Every form Hudum lets an FVS select: mongfontbuilder's MNG locale. */
export const hudumFvsRows: readonly FvsRegistration[] = [
${hudum.map(reg).join('\n')}
];

/** Forms registered only for Todo, Sibe, Manchu or one of the Ali Gali sets. */
export const otherWritingSystemFvsRows: ReadonlyArray<{
  base: number;
  position: JoiningPosition;
  fvs: number;
}> = [
${otherWritingSystems.map((r) => `{ base: ${hex(r.base)}, position: '${r.position}', fvs: ${r.fvs} },`).join('\n')}
];

/** (letter, FVS) pairs UCD ${UNICODE_VERSION} labels "not in use". */
export const notInUseFvsPairs: ReadonlyArray<{ base: number; fvs: number }> = [
${notInUse.map((r) => `{ base: ${hex(r.base)}, fvs: ${r.fvs} },`).join('\n')}
];
`;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  const data = deriveFvs();
  writeFileSync(`${ROOT}${OUT}`, render(data));
  execFileSync('biome', ['format', '--write', OUT], { cwd: ROOT, stdio: 'inherit' });
  process.stdout.write(
    `wrote ${OUT}: ${data.hudum.length} Hudum, ${data.otherWritingSystems.length} other, ` +
      `${data.notInUse.length} not in use\n`,
  );
}
